import { act, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import ChatInput from './ChatInput'

const mocks = vi.hoisted(() => ({ get: vi.fn(), post: vi.fn(), file: vi.fn(), folder: vi.fn() }))
vi.mock('@/lib/api', () => ({ default: { get: mocks.get, post: mocks.post } }))
vi.mock('@/lib/config-form-helpers', () => ({ isDesktopRuntime: () => false, pickFilePath: mocks.file, pickDirectoryPath: mocks.folder }))
beforeEach(() => {
  vi.clearAllMocks(); window.history.replaceState({}, '', '/')
  mocks.file.mockResolvedValue('/tmp/route.csv'); mocks.folder.mockResolvedValue('/tmp/basemap')
  mocks.post.mockImplementation(async (_path, body) => ({ attachments: body.paths.map((path: string) => ({ path, kind: path === '/tmp/basemap' ? 'folder' : 'file' })) }))
  mocks.get.mockImplementation(async path => path === '/api/guides' ? [{ id: 'route', name: '行军路线图', enabled: true }, { id: 'hidden', name: '停用指南', enabled: false }] : { items: [{ id: 'rail', name: '铁路' }] })
})
describe('message inputs', () => {
  it('adds and removes attachment, layer and guide tags, then sends structured references', async () => {
    const send = vi.fn(async () => true)
    render(<ChatInput onSend={send} sessionId="s" instanceId="qgis" />)
    fireEvent.click(screen.getByRole('button', { name: '添加文件' }))
    await screen.findByRole('button', { name: '移除附件 /tmp/route.csv' })
    fireEvent.click(screen.getByRole('button', { name: '添加文件夹' }))
    await screen.findByRole('button', { name: '移除附件 /tmp/basemap' })
    fireEvent.click(screen.getByRole('button', { name: '移除附件 /tmp/route.csv' }))
    fireEvent.change(screen.getByRole('textbox'), { target: { value: '@铁' } })
    fireEvent.click(await screen.findByRole('option', { name: '铁路' }))
    fireEvent.click(screen.getByRole('button', { name: '流程' }))
    fireEvent.click(await screen.findByRole('option', { name: '行军路线图' }))
    expect(screen.queryByRole('option', { name: '停用指南' })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '移除流程' }))
    fireEvent.change(screen.getByRole('textbox'), { target: { value: '/行军' } })
    fireEvent.click(await screen.findByRole('option', { name: '行军路线图' }))
    fireEvent.change(screen.getByRole('textbox'), { target: { value: '制作地图' } })
    fireEvent.click(screen.getByRole('button', { name: '发送' }))
    await waitFor(() => expect(send).toHaveBeenCalledWith('制作地图', { attachments: [{ path: '/tmp/basemap', kind: 'folder' }], layers: [{ id: 'rail', name: '铁路' }], guide_id: 'route' }))
    expect(screen.queryByRole('button', { name: '移除流程' })).not.toBeInTheDocument()
    expect(mocks.get).toHaveBeenCalledWith('/api/instances/qgis/layers')
  })
  it('retains the draft if an attachment disappears before sending', async () => {
    const send = vi.fn()
    render(<ChatInput onSend={send} />)
    fireEvent.click(screen.getByRole('button', { name: '添加文件' }))
    await screen.findByRole('button', { name: '移除附件 /tmp/route.csv' })
    mocks.post.mockRejectedValueOnce(new Error('附件路径不存在'))
    fireEvent.change(screen.getByRole('textbox'), { target: { value: '保留原文' } })
    fireEvent.click(screen.getByRole('button', { name: '发送' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('附件路径不存在')
    expect(send).not.toHaveBeenCalled()
    expect(screen.getByRole('textbox')).toHaveValue('保留原文')
  })
  it('accepts ordinary text while waiting for a clarification and does not submit on IME composition', async () => {
    const send = vi.fn()
    render(<ChatInput onSend={send} running awaitingAnswer />)
    fireEvent.change(screen.getByRole('textbox'), { target: { value: '使用我的文件夹' } })
    fireEvent.keyDown(screen.getByRole('textbox'), { key: 'Enter', isComposing: true })
    expect(send).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: '发送' }))
    await waitFor(() => expect(send).toHaveBeenCalledWith('使用我的文件夹'))
  })
  it('drops stale attachment selection when switching sessions', async () => {
    let resolve!: (value: { attachments: { path: string; kind: 'file' }[] }) => void
    mocks.post.mockReturnValueOnce(new Promise(done => { resolve = done }))
    const view = render(<ChatInput onSend={vi.fn()} sessionId="first" />)
    fireEvent.click(screen.getByRole('button', { name: '添加文件' }))
    await waitFor(() => expect(mocks.post).toHaveBeenCalled())
    view.rerender(<ChatInput onSend={vi.fn()} sessionId="second" />)
    await act(async () => resolve({ attachments: [{ path: '/tmp/route.csv', kind: 'file' }] }))
    expect(screen.queryByRole('button', { name: '移除附件 /tmp/route.csv' })).not.toBeInTheDocument()
  })
})
