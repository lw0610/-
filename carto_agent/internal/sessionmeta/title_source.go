package sessionmeta

import "strings"

const (
	TitleSourceDefault  = "default"
	TitleSourceLLM      = "llm"
	TitleSourceFallback = "fallback"
	TitleSourceManual   = "manual"
)

// NormalizeTitleSource 规范化标题来源值。
func NormalizeTitleSource(value string, fallback string) string {
	switch strings.TrimSpace(strings.ToLower(value)) {
	case TitleSourceDefault:
		return TitleSourceDefault
	case TitleSourceLLM:
		return TitleSourceLLM
	case TitleSourceFallback:
		return TitleSourceFallback
	case TitleSourceManual:
		return TitleSourceManual
	default:
		return NormalizeFallbackTitleSource(fallback)
	}
}

// NormalizeFallbackTitleSource 对回退来源做兜底规范化。
func NormalizeFallbackTitleSource(fallback string) string {
	if strings.EqualFold(strings.TrimSpace(fallback), TitleSourceManual) {
		return TitleSourceManual
	}
	return TitleSourceDefault
}

// InferInitialTitleSource 根据初始命名方式推断标题来源。
func InferInitialTitleSource(nameAutoGenerated bool) string {
	if nameAutoGenerated {
		return TitleSourceDefault
	}
	return TitleSourceManual
}
