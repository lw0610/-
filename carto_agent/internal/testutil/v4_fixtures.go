type V4HTTPResponse struct {
	Status int
	Header http.Header
	Body   []byte
	Delay  time.Duration
}

// V4HTTPServer is loopback-only. A route can model 429s, redirects, and cancellation.
func V4HTTPServer(tb testing.TB, routes map[string]V4HTTPResponse) *httptest.Server {
	tb.Helper()
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		response, ok := routes[r.URL.Path]
		if !ok {
			http.NotFound(w, r)
			return
		}
		if response.Delay > 0 {
			timer := time.NewTimer(response.Delay)
			defer timer.Stop()
			select {
			case <-r.Context().Done():
				return
			case <-timer.C:
			}
		}
		for key, values := range response.Header {
			for _, value := range values {
				w.Header().Add(key, value)
			}
		}
		status := response.Status
		if status == 0 {
			status = http.StatusOK
		}
		w.WriteHeader(status)
		_, _ = w.Write(response.Body)
	}))
	tb.Cleanup(server.Close)
	return server
}

// V4ShapefileZIP returns a synthetic WGS84 point dataset including its sidecars.
func V4ShapefileZIP(tb testing.TB) []byte {
	tb.Helper()
	header := func(words uint32) []byte {
		b := make([]byte, 100)
		binary.BigEndian.PutUint32(b, 9994)
		binary.BigEndian.PutUint32(b[24:], words)
		binary.LittleEndian.PutUint32(b[28:], 1000)
		binary.LittleEndian.PutUint32(b[32:], 1)
		for i, value := range []float64{110, 30, 110, 30} {
			binary.LittleEndian.PutUint64(b[36+i*8:], math.Float64bits(value))
		}
		return b
	}
	shp := append(header(64), make([]byte, 28)...)
	binary.BigEndian.PutUint32(shp[100:], 1)
	binary.BigEndian.PutUint32(shp[104:], 10)
	binary.LittleEndian.PutUint32(shp[108:], 1)
	binary.LittleEndian.PutUint64(shp[112:], math.Float64bits(110))
	binary.LittleEndian.PutUint64(shp[120:], math.Float64bits(30))
	shx := append(header(54), make([]byte, 8)...)
	binary.BigEndian.PutUint32(shx[100:], 50)
	binary.BigEndian.PutUint32(shx[104:], 10)
	dbf := make([]byte, 87)
	dbf[0], dbf[1], dbf[2], dbf[3] = 3, 124, 1, 1
	binary.LittleEndian.PutUint32(dbf[4:], 1)
	binary.LittleEndian.PutUint16(dbf[8:], 65)
	binary.LittleEndian.PutUint16(dbf[10:], 21)
	copy(dbf[32:], "name")
	dbf[43], dbf[48], dbf[64], dbf[65], dbf[86] = 'C', 20, 13, ' ', 26
	copy(dbf[66:86], "synthetic-fixture   ")
	var buffer bytes.Buffer
	writer := zip.NewWriter(&buffer)
	for _, file := range []struct {
		name    string
		content []byte
	}{
		{"fixture.shp", shp}, {"fixture.shx", shx}, {"fixture.dbf", dbf},
		{"fixture.prj", []byte(`GEOGCS["WGS 84",DATUM["WGS_1984",SPHEROID["WGS 84",6378137,298.257223563]],PRIMEM["Greenwich",0],UNIT["degree",0.0174532925199433]]`)},
		{"fixture.cpg", []byte("UTF-8")}, {"SOURCE.txt", []byte("Synthetic test geometry and attributes; generated by AutoCarto tests, CC0-1.0. Not real acquired data.")},
	} {
		entry, err := writer.Create(file.name)
		if err != nil {
			tb.Fatal(err)
		}
		if _, err = entry.Write(file.content); err != nil {
			tb.Fatal(err)
		}
	}
	if err := writer.Close(); err != nil {
		tb.Fatal(err)
	}
	return buffer.Bytes()
}
