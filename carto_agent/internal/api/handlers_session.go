// handleSaveSession PUT /api/sessions/{id}
func (a *API) handleSaveSession(w http.ResponseWriter, r *http.Request) {
	if a.sessionService == nil {
		Error(w, http.StatusServiceUnavailable, "服务未初始化")
		return
	}

	projectPath := r.URL.Query().Get("project_path")

	var sessionData map[string]any
	if err := json.NewDecoder(r.Body).Decode(&sessionData); err != nil {
		Error(w, http.StatusBadRequest, "无效的请求体")
		return
	}

	sessionID := strings.TrimSpace(mux.Vars(r)["id"])
	if bodySessionID, _ := sessionData["session_id"].(string); strings.TrimSpace(bodySessionID) == "" {
		sessionData["session_id"] = sessionID
	} else if strings.TrimSpace(bodySessionID) != sessionID {
		Error(w, http.StatusBadRequest, "session_id 与路径不一致")
		return
	}

	mode, runIntent, err := resolveSessionExecutionModeAndRunIntent(stringValue(sessionData["execution_mode"]), stringValue(sessionData["run_intent"]))
	if err != nil {
		Error(w, http.StatusBadRequest, err.Error())
		return
	}
	sessionData["execution_mode"] = mode
	sessionData["run_intent"] = runIntent
	sessionData["title_source"] = normalizeSessionTitleSource(sessionData)
	a.mergeExistingRuntimeOwnedSessionFields(sessionID, projectPath, sessionData)

	if err := a.sessionService.SaveSession(sessionData, projectPath); err != nil {
		if isSessionValidationError(err) {
			Error(w, http.StatusBadRequest, err.Error())
			return
		}
		Error(w, http.StatusInternalServerError, err.Error())
		return
	}
	Success(w, nil)
}

// handlePatchSession PATCH /api/sessions/{id}
func (a *API) handlePatchSession(w http.ResponseWriter, r *http.Request) {
	if a.sessionService == nil {
		Error(w, http.StatusServiceUnavailable, "服务未初始化")
		return
	}

	sessionID := strings.TrimSpace(mux.Vars(r)["id"])
	if sessionID == "" {
		Error(w, http.StatusBadRequest, "session_id 不能为空")
		return
	}
	projectPath := r.URL.Query().Get("project_path")

	var patch map[string]any
	if err := json.NewDecoder(r.Body).Decode(&patch); err != nil {
		Error(w, http.StatusBadRequest, "无效的请求体")
		return
	}

	allowed := map[string]bool{
		"name":                 true,
		"archived":             true,
		"description":          true,
		"tags":                 true,
		"execution_mode":       true,
		"run_intent":           true,
		"last_message_preview": true,
	}

	sanitizedPatch := make(map[string]any)
	for key, value := range patch {
		if !allowed[key] {
			continue
		}
		if key == "execution_mode" || key == "run_intent" {
			continue
		}
		sanitizedPatch[key] = value
	}

	_, hasExecutionMode := patch["execution_mode"]
	_, hasRunIntent := patch["run_intent"]
	if hasExecutionMode || hasRunIntent {
		mode, runIntent, err := resolveSessionExecutionModeAndRunIntent(stringValue(patch["execution_mode"]), stringValue(patch["run_intent"]))
		if err != nil {
			Error(w, http.StatusBadRequest, err.Error())
			return
		}
		if hasExecutionMode {
			sanitizedPatch["execution_mode"] = mode
			sanitizedPatch["run_intent"] = runIntent
		}
		if hasRunIntent {
			sanitizedPatch["execution_mode"] = mode
			sanitizedPatch["run_intent"] = runIntent
		}
	}

	if len(sanitizedPatch) == 0 {
		sessionData, err := a.sessionService.LoadSession(sessionID, projectPath)
		if err != nil {
			Error(w, http.StatusNotFound, err.Error())
			return
		}
		sessionData, err = ensureSessionModeFields(sessionData)
		if err != nil {
			Error(w, http.StatusBadRequest, err.Error())
			return
		}
		Success(w, sessionData)
		return
	}

	updated, err := a.sessionService.SaveSessionAtomically(sessionID, projectPath, func(sessionData map[string]any) error {
		for key, value := range sanitizedPatch {
			sessionData[key] = value
		}
		if _, hasName := sanitizedPatch["name"]; hasName {
			sessionData["name_auto_generated"] = false
			sessionData["title_source"] = sessionmeta.TitleSourceManual
		}
		sessionData["updated_at"] = time.Now().Format(time.RFC3339)
		return nil
	})
	if err != nil {
		if strings.Contains(err.Error(), "读取会话文件失败") || strings.Contains(err.Error(), "会话不存在") {
			Error(w, http.StatusNotFound, err.Error())
			return
		}
		if isSessionValidationError(err) {
			Error(w, http.StatusBadRequest, err.Error())
			return
		}
		Error(w, http.StatusInternalServerError, err.Error())
		return
	}
	a.realtimeHub.BroadcastSessionChange("updated", sessionID, map[string]any{
		"project_path": strings.TrimSpace(projectPath),
	})

	updated, err = ensureSessionModeFields(updated)
	if err != nil {
		Error(w, http.StatusBadRequest, err.Error())
		return
	}
	Success(w, updated)
}

// handleSessionOperation POST /api/sessions/{id}/operations
func (a *API) handleSessionOperation(w http.ResponseWriter, r *http.Request) {
	if a.sessionService == nil {
		Error(w, http.StatusServiceUnavailable, "服务未初始化")
		return
	}

	sessionID := strings.TrimSpace(mux.Vars(r)["id"])
	if sessionID == "" {
		Error(w, http.StatusBadRequest, "session_id 不能为空")
		return
	}

	var body struct {
		Operation   map[string]any `json:"operation"`
		Session     map[string]any `json:"session"`
		ProjectPath string         `json:"project_path"`
	}
	if err := json.NewDecoder(r.Body).Decode(&body); err != nil {
		Error(w, http.StatusBadRequest, "无效的请求体")
		return
	}

	opType, _ := body.Operation["type"].(string)
	if strings.TrimSpace(opType) == "" {
		Error(w, http.StatusBadRequest, "operation.type 不能为空")
		return
	}

	projectPath := strings.TrimSpace(r.URL.Query().Get("project_path"))
	if projectPath == "" {
		Error(w, http.StatusBadRequest, "project_path 不能为空")
		return
	}

	sessionData := body.Session
	if sessionData == nil {
		loaded, err := a.sessionService.LoadSession(sessionID, projectPath)
		if err != nil {
			Error(w, http.StatusNotFound, err.Error())
			return
		}
		sessionData = loaded
	}

	if bodySessionID, _ := sessionData["session_id"].(string); strings.TrimSpace(bodySessionID) == "" {
		sessionData["session_id"] = sessionID
	} else if strings.TrimSpace(bodySessionID) != sessionID {
		Error(w, http.StatusBadRequest, "session_id 与路径不一致")
		return
	}

	sessionData["updated_at"] = time.Now().Format(time.RFC3339)
	a.mergeExistingRuntimeOwnedSessionFields(sessionID, projectPath, sessionData)

	if err := a.sessionService.SaveSessionWithOperation(sessionData, projectPath, body.Operation); err != nil {
		if isSessionValidationError(err) {
			Error(w, http.StatusBadRequest, err.Error())
			return
		}
		Error(w, http.StatusInternalServerError, err.Error())
		return
	}

	updated, err := a.sessionService.LoadSession(sessionID, projectPath)
	if err != nil {
		Error(w, http.StatusInternalServerError, err.Error())
		return
	}
	a.realtimeHub.BroadcastSessionChange("updated", sessionID, map[string]any{
		"project_path": strings.TrimSpace(projectPath),
		"operation":    strings.TrimSpace(opType),
	})

	Success(w, updated)
}

// handleDeleteSession DELETE /api/sessions/{id}
func (a *API) handleDeleteSession(w http.ResponseWriter, r *http.Request) {
	if a.sessionService == nil {
		Error(w, http.StatusServiceUnavailable, "服务未初始化")
		return
	}

	sessionID := mux.Vars(r)["id"]
	projectPath := r.URL.Query().Get("project_path")

	if err := a.sessionService.DeleteSession(sessionID, projectPath); err != nil {
		if strings.Contains(err.Error(), "会话不存在") {
			Error(w, http.StatusNotFound, err.Error())
			return
		}
		if isSessionValidationError(err) {
			Error(w, http.StatusBadRequest, err.Error())
			return
		}
		Error(w, http.StatusInternalServerError, err.Error())
		return
	}
	a.realtimeHub.BroadcastSessionChange("deleted", strings.TrimSpace(sessionID), map[string]any{
		"project_path": strings.TrimSpace(projectPath),
	})
	Success(w, nil)
}

