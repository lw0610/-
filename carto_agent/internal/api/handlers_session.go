func defaultSessionName(now time.Time) string {
	return "会话 " + now.Format("01-02 15:04")
}

func normalizeSessionExecutionModeOrDefault(mode string) string {
	normalized := config.NormalizeSessionExecutionMode(mode)
	if normalized == "" {
		return "build"
	}
	return normalized
}

func normalizeSessionRunIntentOrDefault(intent string) string {
	normalized := config.NormalizeSessionRunIntent(intent)
	if normalized == "" {
		return "execute"
	}
	return normalized
}

func invalidExecutionModeError(mode string) error {
	trimmed := strings.TrimSpace(mode)
	if trimmed == "" {
		return fmt.Errorf("execution_mode 不能为空，仅支持 build / plan")
	}
	return fmt.Errorf("execution_mode=%s 已废弃或无效，仅支持 build / plan", trimmed)
}

func invalidRunIntentError(runIntent string) error {
	trimmed := strings.TrimSpace(runIntent)
	if trimmed == "" {
		return fmt.Errorf("run_intent 不能为空，仅支持 execute / plan_only")
	}
	return fmt.Errorf("run_intent=%s 已废弃或无效，仅支持 execute / plan_only", trimmed)
}

func resolveSessionExecutionModeAndRunIntent(executionMode string, runIntent string) (string, string, error) {
	if normalizedIntent := config.NormalizeSessionRunIntent(runIntent); normalizedIntent != "" {
		mode := config.RunIntentToExecutionMode(normalizedIntent)
		if mode == "" {
			return "", "", invalidRunIntentError(runIntent)
		}
		if strings.TrimSpace(executionMode) != "" {
			normalizedMode := config.NormalizeSessionExecutionMode(executionMode)
			if normalizedMode == "" {
				return "", "", invalidExecutionModeError(executionMode)
			}
			if normalizedMode != mode {
				return "", "", fmt.Errorf("execution_mode 与 run_intent 不一致")
			}
		}
		return mode, normalizedIntent, nil
	}
	if strings.TrimSpace(runIntent) != "" {
		return "", "", invalidRunIntentError(runIntent)
	}

	if strings.TrimSpace(executionMode) == "" {
		return "build", "execute", nil
	}

	normalizedMode := config.NormalizeSessionExecutionMode(executionMode)
	if normalizedMode == "" {
		return "", "", invalidExecutionModeError(executionMode)
	}
	normalizedIntent := config.ExecutionModeToRunIntent(normalizedMode)
	if normalizedIntent == "" {
		return "", "", invalidExecutionModeError(executionMode)
	}
	return normalizedMode, normalizedIntent, nil
}

func sanitizeExportFileName(name string) string {
	trimmed := strings.TrimSpace(name)
	if trimmed == "" {
		return "session"
	}
	replacer := strings.NewReplacer(
		"/", "_",
		"\\", "_",
		":", "_",
		"*", "_",
		"?", "_",
		"\"", "_",
		"<", "_",
		">", "_",
		"|", "_",
	)
	cleaned := replacer.Replace(trimmed)
	if cleaned == "" {
		return "session"
	}
	return cleaned
}

func sanitizeSessionForExport(session map[string]any) map[string]any {
	if session == nil {
		return nil
	}

	cleaned := make(map[string]any, len(session))
	for key, value := range session {
		cleaned[key] = value
	}

	rawConfig, ok := cleaned["llm_config"].(map[string]any)
	if !ok || rawConfig == nil {
		return cleaned
	}

	filteredConfig := make(map[string]any, len(rawConfig))
	for key, value := range rawConfig {
		lower := strings.ToLower(key)
		if strings.Contains(lower, "key") || strings.Contains(lower, "token") || strings.Contains(lower, "secret") || strings.Contains(lower, "password") {
			continue
		}
		filteredConfig[key] = value
	}
	cleaned["llm_config"] = filteredConfig
	return cleaned
}

func stringValue(raw any) string {
	text, _ := raw.(string)
	return strings.TrimSpace(text)
}

func isLikelyDefaultSessionName(name string) bool {
	trimmed := strings.TrimSpace(name)
	if trimmed == "" {
		return true
	}
	lower := strings.ToLower(trimmed)
	return strings.HasPrefix(trimmed, "会话 ") || strings.HasPrefix(lower, "session ")
}

func inferSessionTitleSourceFallback(session map[string]any) string {
	if session == nil {
		return sessionmeta.TitleSourceDefault
	}
	if autoGenerated, ok := session["name_auto_generated"].(bool); ok && autoGenerated {
		return sessionmeta.TitleSourceDefault
	}
	if isLikelyDefaultSessionName(stringValue(session["name"])) {
		return sessionmeta.TitleSourceDefault
	}
	return sessionmeta.TitleSourceManual
}

func normalizeSessionTitleSource(session map[string]any) string {
	return sessionmeta.NormalizeTitleSource(stringValue(session["title_source"]), inferSessionTitleSourceFallback(session))
}

func ensureSessionModeFields(session map[string]any) (map[string]any, error) {
	if session == nil {
		return nil, nil
	}

	rawMode := stringValue(session["execution_mode"])
	rawRunIntent := stringValue(session["run_intent"])
	if strings.EqualFold(strings.TrimSpace(rawMode), "auto") || strings.EqualFold(strings.TrimSpace(rawRunIntent), "auto") {
		session["execution_mode"] = "build"
		session["run_intent"] = "execute"
		return session, nil
	}

	mode, runIntent, err := resolveSessionExecutionModeAndRunIntent(rawMode, rawRunIntent)
	if err != nil {
		return nil, err
	}
	session["execution_mode"] = mode
	session["run_intent"] = runIntent
	session["title_source"] = normalizeSessionTitleSource(session)
	return session, nil
}

func ensureSessionListModeFields(sessions []map[string]any) ([]map[string]any, error) {
	for idx := range sessions {
		normalized, err := ensureSessionModeFields(sessions[idx])
		if err != nil {
			return nil, err
		}
		sessions[idx] = normalized
	}
	return sessions, nil
}

func isSessionValidationError(err error) bool {
	if err == nil {
		return false
	}
	text := err.Error()
	return strings.Contains(text, "会话ID") || strings.Contains(text, "project_path") || strings.Contains(text, "格式非法") || strings.Contains(text, "非法路径")
}

func sessionProjectName(projectPath string) string {
	trimmed := strings.TrimSpace(projectPath)
	if trimmed == "" {
		return "未命名项目"
	}

	name := filepath.Base(trimmed)
	if ext := filepath.Ext(name); ext != "" {
		name = strings.TrimSuffix(name, ext)
	}
	name = strings.TrimSpace(name)
	if name == "" || name == "." {
		return "未命名项目"
	}
	return name
}

func formatSessionNameByPattern(pattern, projectPath string, seq int, now time.Time) string {
	pattern = strings.TrimSpace(pattern)
	if pattern == "" {
		return defaultSessionName(now)
	}

	if seq <= 0 {
		seq = 1
	}
	seqText := fmt.Sprintf("%03d", seq)
	projectName := sessionProjectName(projectPath)

	replacements := []struct {
		token string
		value string
	}{
		{token: "{project}", value: projectName},
		{token: "{seq}", value: seqText},
		{token: "{date}", value: now.Format("01-02 15:04")},
		{token: "项目名", value: projectName},
		{token: "序号", value: seqText},
		{token: "YYYY", value: now.Format("2006")},
		{token: "YY", value: now.Format("06")},
		{token: "MM", value: now.Format("01")},
		{token: "DD", value: now.Format("02")},
		{token: "HH", value: now.Format("15")},
		{token: "mm", value: now.Format("04")},
		{token: "ss", value: now.Format("05")},
	}

	result := pattern
	for _, item := range replacements {
		result = strings.ReplaceAll(result, item.token, item.value)
	}
	result = strings.TrimSpace(result)
	if result == "" {
		return defaultSessionName(now)
	}
	return result
}

type sessionCreateDefaults struct {
	namePattern   string
	executionMode string
	runIntent     string
	nextSeq       int
}

func (a *API) resolveSessionCreateDefaults(projectPath string) sessionCreateDefaults {
	result := sessionCreateDefaults{
		namePattern:   "会话 MM-DD HH:mm",
		executionMode: "build",
		runIntent:     "execute",
		nextSeq:       1,
	}

	if a.configService != nil {
		if cfg, err := a.configService.GetFullConfig(); err == nil && cfg != nil {
			if pattern := strings.TrimSpace(cfg.Session.DefaultNamePattern); pattern != "" {
				result.namePattern = pattern
			}
			result.executionMode = normalizeSessionExecutionModeOrDefault(cfg.Session.DefaultExecutionMode)
			result.runIntent = normalizeSessionRunIntentOrDefault(config.ExecutionModeToRunIntent(result.executionMode))
		}
	}

	if a.sessionService != nil {
		if sessions, err := a.sessionService.ListSessions(projectPath); err == nil {
			result.nextSeq = len(sessions) + 1
		}
	}

	return result
}

func buildDefaultSessionData(sessionID, name, projectPath, executionMode string, nameAutoGenerated bool) map[string]any {
	now := time.Now()
	if strings.TrimSpace(name) == "" {
		name = defaultSessionName(now)
	}
	executionMode = normalizeSessionExecutionModeOrDefault(executionMode)
	runIntent := normalizeSessionRunIntentOrDefault(config.ExecutionModeToRunIntent(executionMode))
	ts := now.Format(time.RFC3339)

	return map[string]any{
		"session_id":           sessionID,
		"name":                 name,
		"name_auto_generated":  nameAutoGenerated,
		"title_source":         sessionmeta.InferInitialTitleSource(nameAutoGenerated),
		"created_at":           ts,
		"updated_at":           ts,
		"project_path":         projectPath,
		"llm_config":           map[string]any{},
		"execution_mode":       executionMode,
		"run_intent":           runIntent,
		"messages":             []any{},
		"tool_calls":           []any{},
		"snapshots":            []any{},
		"context_stats":        map[string]any{"total_tokens": 0, "compressed_count": 0},
		"tags":                 []any{},
		"archived":             false,
		"description":          "",
		"last_message_preview": "",
		"total_tokens_used":    0,
		"compression_history":  []any{},
	}
}

// handleListSessions GET /api/sessions
func (a *API) handleListSessions(w http.ResponseWriter, r *http.Request) {
	if a.sessionService == nil {
		Error(w, http.StatusServiceUnavailable, "服务未初始化")
		return
	}

	projectPath := r.URL.Query().Get("project_path")
	sessions, err := a.sessionService.ListSessions(projectPath)
	if err != nil {
		Error(w, http.StatusInternalServerError, err.Error())
		return
	}
	sessions, err = ensureSessionListModeFields(sessions)
	if err != nil {
		Error(w, http.StatusBadRequest, err.Error())
		return
	}
	Success(w, map[string]any{"sessions": sessions})
}

var runtimeOwnedSessionFieldKeys = []string{
	"workflow_blocks",
	"runtime_status",
	"run_id",
	"runtime_phase",
	"bound_instance_id",
	"bound_project_path",
	"checkpoint_id",
	"runtime_revision",
	"active_agent_config",
	"last_error",
	"runtime_failure_code",
	"runtime_failure_reason",
	"runtime_summary",
}

func preserveRuntimeOwnedSessionFields(target, source map[string]any) {
	if target == nil {
		return
	}
	for _, key := range runtimeOwnedSessionFieldKeys {
		if source != nil {
			if value, ok := source[key]; ok {
				target[key] = value
				continue
			}
		}
		delete(target, key)
	}
}

func (a *API) mergeExistingRuntimeOwnedSessionFields(sessionID, projectPath string, target map[string]any) {
	if a == nil || a.sessionService == nil || target == nil {
		return
	}
	existing, err := a.sessionService.LoadSession(sessionID, projectPath)
	if err != nil {
		return
	}
	preserveRuntimeOwnedSessionFields(target, existing)
}

// handleCreateSession POST /api/sessions
func (a *API) handleCreateSession(w http.ResponseWriter, r *http.Request) {
	if a.sessionService == nil {
		Error(w, http.StatusServiceUnavailable, "服务未初始化")
		return
	}

	var body struct {
		SessionID   string `json:"session_id"`
		Name        string `json:"name"`
		ProjectPath string `json:"project_path"`
	}
	if err := json.NewDecoder(r.Body).Decode(&body); err != nil {
		Error(w, http.StatusBadRequest, "无效的请求体")
		return
	}

	sessionID := strings.TrimSpace(body.SessionID)
	if sessionID == "" {
		sessionID = uuid.NewString()
	}

	projectPath := strings.TrimSpace(r.URL.Query().Get("project_path"))
	if projectPath == "" {
		Error(w, http.StatusBadRequest, "project_path 不能为空")
		return
	}
	defaults := a.resolveSessionCreateDefaults(projectPath)
	name := strings.TrimSpace(body.Name)
	nameAutoGenerated := false
	if name == "" {
		nameAutoGenerated = true
		name = formatSessionNameByPattern(defaults.namePattern, projectPath, defaults.nextSeq, time.Now())
	}

	sessionData := buildDefaultSessionData(sessionID, name, projectPath, defaults.executionMode, nameAutoGenerated)
	if err := a.sessionService.SaveSession(sessionData, projectPath); err != nil {
		if isSessionValidationError(err) {
			Error(w, http.StatusBadRequest, err.Error())
			return
		}
		Error(w, http.StatusInternalServerError, err.Error())
		return
	}
	if _, err := a.sessionService.InitSessionDir(projectPath, sessionID); err != nil {
		if isSessionValidationError(err) {
			Error(w, http.StatusBadRequest, err.Error())
			return
		}
		Error(w, http.StatusInternalServerError, err.Error())
		return
	}
	a.realtimeHub.BroadcastSessionChange("created", sessionID, map[string]any{
		"project_path": strings.TrimSpace(projectPath),
	})

	Success(w, sessionData)
}

// handleImportSession POST /api/sessions/import
func (a *API) handleImportSession(w http.ResponseWriter, r *http.Request) {
	if a.sessionService == nil {
		Error(w, http.StatusServiceUnavailable, "服务未初始化")
		return
	}

	var body struct {
		Session     map[string]any `json:"session"`
		ProjectPath string         `json:"project_path"`
	}
	if err := json.NewDecoder(r.Body).Decode(&body); err != nil {
		Error(w, http.StatusBadRequest, "无效的请求体")
		return
	}
	if body.Session == nil {
		Error(w, http.StatusBadRequest, "session 不能为空")
		return
	}

	rawMessages, ok := body.Session["messages"]
	if !ok {
		Error(w, http.StatusBadRequest, "session.messages 不能为空")
		return
	}
	if _, ok := rawMessages.([]any); !ok {
		Error(w, http.StatusBadRequest, "session.messages 必须是数组")
		return
	}

	projectPath := strings.TrimSpace(r.URL.Query().Get("project_path"))
	if projectPath == "" {
		Error(w, http.StatusBadRequest, "project_path 不能为空")
		return
	}

	defaults := a.resolveSessionCreateDefaults(projectPath)
	newSessionID := uuid.NewString()
	now := time.Now()
	nowText := now.Format(time.RFC3339)

	name := ""
	if rawName, _ := body.Session["name"].(string); strings.TrimSpace(rawName) != "" {
		name = strings.TrimSpace(rawName)
	}
	nameAutoGenerated := false
	if name == "" {
		nameAutoGenerated = true
		name = formatSessionNameByPattern(defaults.namePattern, projectPath, defaults.nextSeq, now)
	}

	mode := defaults.executionMode
	runIntent := defaults.runIntent
	if rawIntent, _ := body.Session["run_intent"].(string); strings.TrimSpace(rawIntent) != "" {
		var resolveErr error
		mode, runIntent, resolveErr = resolveSessionExecutionModeAndRunIntent("", rawIntent)
		if resolveErr != nil {
			Error(w, http.StatusBadRequest, resolveErr.Error())
			return
		}
	} else if rawMode, _ := body.Session["execution_mode"].(string); strings.TrimSpace(rawMode) != "" {
		var resolveErr error
		mode, runIntent, resolveErr = resolveSessionExecutionModeAndRunIntent(rawMode, "")
		if resolveErr != nil {
			Error(w, http.StatusBadRequest, resolveErr.Error())
			return
		}
	}

	imported := buildDefaultSessionData(newSessionID, name, projectPath, mode, nameAutoGenerated)
	for key, value := range body.Session {
		imported[key] = value
	}

	imported["session_id"] = newSessionID
	imported["name"] = name
	imported["name_auto_generated"] = nameAutoGenerated
	imported["title_source"] = normalizeSessionTitleSource(imported)
	imported["project_path"] = projectPath
	imported["execution_mode"] = mode
	imported["run_intent"] = runIntent
	imported["created_at"] = nowText
	imported["updated_at"] = nowText

	if err := a.sessionService.SaveSession(imported, projectPath); err != nil {
		if isSessionValidationError(err) {
			Error(w, http.StatusBadRequest, err.Error())
			return
		}
		Error(w, http.StatusInternalServerError, err.Error())
		return
	}
	if _, err := a.sessionService.InitSessionDir(projectPath, newSessionID); err != nil {
		if isSessionValidationError(err) {
			Error(w, http.StatusBadRequest, err.Error())
			return
		}
		Error(w, http.StatusInternalServerError, err.Error())
		return
	}
	a.realtimeHub.BroadcastSessionChange("created", newSessionID, map[string]any{
		"project_path": strings.TrimSpace(projectPath),
	})

	Success(w, imported)
}

